import { Link } from 'wouter';
import type { CashGuardSummary, DataSource } from '@/api/types';
import { AiBadge } from '@/components/AiBadge';
import { Card } from '@/components/Card';
import { formatDateTime } from '@/lib/format';

const SOURCE_LINK: Record<DataSource, string> = {
  PAYROLL: '#breakdown',
  SALES: '#breakdown',
  RECEIVABLES: '/receivables',
  BILLS: '/bills',
  PURCHASES: '/bills',
};

const CHIP = 'inline-flex rounded-full border border-line px-2.5 py-1 text-xs hover:border-accent hover:text-accent';

export function AiExplanationCard({ ai }: { ai: CashGuardSummary['ai'] }) {
  return (
    <Card title="Why this is happening" action={<AiBadge fallback={ai.isFallback} />}>
      <p className="text-sm leading-relaxed">{ai.explanation}</p>
      {ai.isFallback && (
        <p className="mt-3 rounded-input bg-canvas p-3 text-xs text-muted">
          The AI is unavailable, so this summary comes from fixed rules. Message drafts are templates. The numbers are unaffected.
        </p>
      )}

      <div className="mt-4">
        <p className="text-xs text-muted">Based on:</p>
        <ul className="mt-2 flex flex-wrap gap-2">
          {ai.basedOn.map((item) => (
            <li key={item.label}>
              {SOURCE_LINK[item.source].startsWith('#') ? (
                <a href={SOURCE_LINK[item.source]} className={CHIP}>
                  {item.label}
                </a>
              ) : (
                <Link href={SOURCE_LINK[item.source]} className={CHIP}>
                  {item.label}
                </Link>
              )}
            </li>
          ))}
        </ul>
      </div>

      <p className="mt-4 text-xs text-muted">
        {ai.isFallback ? 'Rules-based' : `Generated by ${ai.model}`} · {formatDateTime(ai.generatedAt)}
      </p>
    </Card>
  );
}
